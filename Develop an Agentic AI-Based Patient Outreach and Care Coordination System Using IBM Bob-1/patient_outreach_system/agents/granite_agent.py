"""
agents/granite_agent.py

IBM Granite AI integration for generating patient outreach explanations.
Uses a local rule-based fallback when the Granite API is unavailable
so the application always works even without an API key.
"""

import os
import json
from typing import Optional

# ─── Try to import httpx for real Granite calls ──────────────────────────────
try:
    import httpx
    HTTPX_AVAILABLE = True
except ImportError:
    HTTPX_AVAILABLE = False

GRANITE_API_KEY = os.getenv("GRANITE_API_KEY", "")
GRANITE_API_URL = os.getenv(
    "GRANITE_API_URL",
    "https://us-south.ml.cloud.ibm.com/ml/v1/text/generation?version=2023-05-29"
)


# ─── Rule-based fallback ──────────────────────────────────────────────────────

def _rule_based_explanation(patient_data: dict) -> str:
    """
    Generate a structured, plain-English explanation using clinical rules.
    This powers the system when Granite is not configured.
    """
    name         = patient_data.get("name", "This patient")
    age          = patient_data.get("age", "unknown age")
    condition    = patient_data.get("condition", "chronic condition")
    hba1c        = patient_data.get("hba1c", 0)
    bp           = patient_data.get("blood_pressure", "N/A")
    risk_score   = patient_data.get("ai_risk_score", 0)
    risk_level   = patient_data.get("reviewed_risk_level") or patient_data.get("ai_risk_level", "Unknown")
    last_visit   = patient_data.get("last_visit", "unknown date")
    missing_raw  = patient_data.get("missing_data_flags", "[]")
    language     = patient_data.get("language", "English")

    try:
        missing = json.loads(missing_raw) if isinstance(missing_raw, str) else missing_raw
    except Exception:
        missing = []

    lines = [
        f"**AI-Assisted Outreach Explanation for {name}**",
        "",
        f"**Patient Overview:** {name}, aged {age}, is currently being managed for {condition}. "
        f"Their last recorded clinical visit was on {last_visit}.",
        "",
    ]

    # HbA1c assessment
    if hba1c >= 9.0:
        lines.append(
            f"**Glycaemic Control:** HbA1c is {hba1c}%, which is significantly above the recommended target "
            f"of 7.0%. This level indicates poor blood sugar control and substantially increases the risk of "
            f"diabetes-related complications including nerve damage, kidney disease, and eye problems."
        )
    elif hba1c >= 7.5:
        lines.append(
            f"**Glycaemic Control:** HbA1c is {hba1c}%, which is above the recommended 7.0% target. "
            f"Closer monitoring and possible treatment adjustment are warranted."
        )
    elif hba1c > 0:
        lines.append(
            f"**Glycaemic Control:** HbA1c is {hba1c}%, which is near or within the target range. "
            f"Current management appears to be working well."
        )

    # Blood pressure
    lines.append(
        f"\n**Blood Pressure:** Recorded as {bp}. "
        + ("This is elevated and increases cardiovascular risk alongside diabetes."
           if any(int(x) > 130 for x in bp.split("/") if x.isdigit()) else
           "This is within an acceptable range.")
    )

    # Risk scoring
    lines.append(
        f"\n**AI Risk Assessment:** The AI risk model assigned a score of {risk_score:.1f}/100, "
        f"placing this patient in the **{risk_level}** category. "
    )

    if risk_level in ("Urgent", "High"):
        lines.append(
            "This score reflects several co-existing risk factors. The care team should prioritise "
            "outreach and ensure clinical review occurs promptly."
        )
    elif risk_level == "Medium":
        lines.append(
            "This score indicates moderate risk. Proactive contact and monitoring are recommended "
            "to prevent escalation."
        )
    else:
        lines.append(
            "Risk is currently low. Routine monitoring and preventive outreach are appropriate."
        )

    # Missing data
    if missing:
        lines.append(f"\n**Information Gaps Identified:** The following items are missing or overdue:")
        for item in missing:
            lines.append(f"  - {item}")
        lines.append(
            "These gaps should be resolved at the next clinical contact to ensure complete care."
        )

    # Language
    if language != "English":
        lines.append(
            f"\n**Communication Note:** The patient's primary language is {language}. "
            f"Outreach materials and clinical communication should be arranged in {language}, "
            f"and an interpreter or bilingual navigator should be involved."
        )

    lines.append(
        "\n**Important Guardrail:** This explanation is generated by an AI assistant to support "
        "care coordination planning. It does not constitute a clinical diagnosis or treatment "
        "recommendation. All outreach actions must be reviewed and approved by a qualified "
        "healthcare professional before implementation."
    )

    return "\n".join(lines)


# ─── Risk Review Agent ────────────────────────────────────────────────────────

def review_ai_risk_ranking(patient_data: dict) -> dict:
    """
    Risk Ranking Review Agent: examines the AI score and flags inconsistencies.
    Returns a dict with findings and a suggested reviewed_risk_level.
    """
    hba1c      = patient_data.get("hba1c", 0)
    ai_score   = patient_data.get("ai_risk_score", 0)
    ai_level   = patient_data.get("ai_risk_level", "Low")
    missing_raw= patient_data.get("missing_data_flags", "[]")
    condition  = patient_data.get("condition", "")

    try:
        missing = json.loads(missing_raw) if isinstance(missing_raw, str) else missing_raw
    except Exception:
        missing = []

    findings   = []
    suggested  = ai_level

    # Rule: HbA1c > 9 → at least High
    if hba1c >= 10.0 and ai_level not in ("Urgent", "High"):
        findings.append(f"HbA1c {hba1c}% is critically elevated – risk may be understated as {ai_level}.")
        suggested = "Urgent"
    elif hba1c >= 9.0 and ai_level == "Low":
        findings.append(f"HbA1c {hba1c}% is high; Low risk label appears inconsistent.")
        suggested = "Medium"

    # Rule: missing data increases uncertainty
    if len(missing) >= 2:
        findings.append(f"{len(missing)} missing data items reduce confidence in the AI ranking.")

    # Rule: CKD or CHD compound risk
    if "CKD" in condition or "CHD" in condition:
        findings.append("Co-morbidity (CKD/CHD) may not be fully weighted in the AI score.")
        if suggested in ("Low", "Medium"):
            suggested = "High"

    # No issues found
    if not findings:
        findings.append("AI risk ranking appears consistent with available clinical indicators.")

    return {
        "original_level": ai_level,
        "suggested_level": suggested,
        "findings": findings,
        "consistent": len(findings) == 1 and "consistent" in findings[0],
    }


# ─── Care Barrier Agent ───────────────────────────────────────────────────────

def identify_care_barriers(barriers: list) -> dict:
    """
    Care Barrier Identification Agent: summarises documented barriers and
    recommends mitigation actions.
    """
    if not barriers:
        return {
            "summary": "No documented care barriers on record.",
            "high_severity_count": 0,
            "recommendations": [],
        }

    high_count = sum(1 for b in barriers if b.get("severity") == "High")
    recommendations = []

    for b in barriers:
        btype = b.get("barrier_type", "")
        sev   = b.get("severity", "")
        if btype == "Transportation":
            recommendations.append("Arrange accessible medical transport or telehealth alternative.")
        elif btype == "Language":
            recommendations.append("Assign bilingual navigator or certified medical interpreter.")
        elif btype == "Financial":
            recommendations.append("Connect patient with prescription assistance and benefits advisory.")
        elif btype == "Social Isolation":
            recommendations.append("Involve social worker; establish emergency contact and welfare check schedule.")
        elif btype == "Cultural":
            recommendations.append("Review cultural preferences; adjust care team composition where possible.")
        elif btype == "Health Literacy":
            recommendations.append("Provide simplified written materials and in-person explanation support.")

    # De-duplicate
    recommendations = list(dict.fromkeys(recommendations))

    return {
        "summary": (
            f"{len(barriers)} barrier(s) documented. "
            f"{high_count} are rated High severity and require priority attention."
        ),
        "high_severity_count": high_count,
        "recommendations": recommendations,
    }


# ─── Outreach Planning Agent ──────────────────────────────────────────────────

def generate_outreach_plan(patient_data: dict, barriers: list) -> dict:
    """
    Outreach Planning Agent: recommends contact method, next steps,
    responsible role, and follow-up timeline.
    """
    risk_level  = patient_data.get("reviewed_risk_level") or patient_data.get("ai_risk_level", "Low")
    language    = patient_data.get("language", "English")
    has_transport_barrier = any(b.get("barrier_type") == "Transportation" for b in barriers)
    has_language_barrier  = any(b.get("barrier_type") == "Language" for b in barriers)

    # Contact method
    if risk_level == "Urgent" or has_transport_barrier:
        contact_method = "Home Visit"
    elif has_language_barrier:
        contact_method = "Phone"
    else:
        contact_method = "Phone" if risk_level == "High" else "Email"

    # Follow-up window
    follow_up_days = {"Urgent": 3, "High": 14, "Medium": 30, "Low": 60}.get(risk_level, 30)

    from datetime import date, timedelta
    follow_up_date = (date.today() + timedelta(days=follow_up_days)).isoformat()

    # Responsible role
    if risk_level == "Urgent":
        role = "GP + Social Worker"
    elif risk_level == "High":
        role = "Care Coordinator"
    elif has_language_barrier:
        role = "Community Health Worker"
    else:
        role = "Practice Nurse"

    # Next step narrative
    steps = []
    if risk_level in ("Urgent", "High"):
        steps.append("Schedule priority clinical review.")
    if has_transport_barrier:
        steps.append("Arrange accessible transport or telehealth appointment.")
    if has_language_barrier:
        steps.append(f"Assign {language}-speaking navigator before outreach contact.")
    if not steps:
        steps.append("Send routine review reminder and health information materials.")

    return {
        "contact_method":   contact_method,
        "next_step":        " ".join(steps),
        "responsible_role": role,
        "follow_up_date":   follow_up_date,
        "rationale":        _rule_based_explanation(patient_data),
    }


# ─── Escalation Agent ────────────────────────────────────────────────────────

def should_escalate(patient_data: dict, barriers: list) -> dict:
    """
    Escalation Agent: determines whether a case requires immediate
    escalation to a senior clinician.
    """
    hba1c      = patient_data.get("hba1c", 0)
    risk_level = patient_data.get("reviewed_risk_level") or patient_data.get("ai_risk_level", "Low")
    missing_raw= patient_data.get("missing_data_flags", "[]")

    try:
        missing = json.loads(missing_raw) if isinstance(missing_raw, str) else missing_raw
    except Exception:
        missing = []

    reasons = []

    if hba1c >= 10.0:
        reasons.append(f"Critically elevated HbA1c ({hba1c}%) requiring urgent clinical review.")
    if risk_level == "Urgent":
        reasons.append("Patient classified as Urgent risk by care team review.")
    if any(b.get("barrier_type") == "Social Isolation" for b in barriers):
        reasons.append("Patient lives alone with no recorded emergency contact – welfare risk.")
    if len(missing) >= 2 and risk_level in ("High", "Urgent"):
        reasons.append(f"{len(missing)} missing clinical data items in a high-risk patient.")

    return {
        "escalate": len(reasons) > 0,
        "urgency": "Urgent" if reasons else "None",
        "reasons": reasons,
    }


# ─── Main explanation entry point ─────────────────────────────────────────────

def get_granite_explanation(patient_data: dict) -> str:
    """
    Returns an AI-generated explanation for a patient.
    Tries IBM Granite API first; falls back to rule-based engine.
    """
    if HTTPX_AVAILABLE and GRANITE_API_KEY:
        try:
            prompt = (
                f"You are a care coordination AI assistant. Provide a clear, person-centred, "
                f"evidence-based explanation of why the following patient needs outreach, "
                f"what their key risk factors are, and what a care coordinator should do next. "
                f"Always remind the reader that clinical decisions must involve a qualified professional.\n\n"
                f"Patient data: {json.dumps(patient_data, indent=2)}"
            )
            headers = {
                "Authorization": f"Bearer {GRANITE_API_KEY}",
                "Content-Type": "application/json",
            }
            body = {
                "model_id": "ibm/granite-13b-instruct-v2",
                "input": prompt,
                "parameters": {"decoding_method": "greedy", "max_new_tokens": 400},
            }
            response = httpx.post(GRANITE_API_URL, json=body, headers=headers, timeout=15)
            response.raise_for_status()
            data = response.json()
            text = data["results"][0]["generated_text"]
            return text + "\n\n*(Generated by IBM Granite)*"
        except Exception as exc:
            # Fall through to rule-based
            pass

    return _rule_based_explanation(patient_data) + "\n\n*(Generated by AI Rule Engine – IBM Granite not configured)*"
